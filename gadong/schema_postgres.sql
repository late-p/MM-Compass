-- MM-Compass 전용 Supabase 프로젝트에서 실행한다.
-- 애플리케이션 서버가 직접 PostgreSQL에 연결하며 브라우저 Data API에는 공개하지 않는다.
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL, display TEXT NOT NULL, pw_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'uploader', 'viewer')),
    dept TEXT DEFAULT '', active INTEGER DEFAULT 1,
    fail_count INTEGER DEFAULT 0, locked_until TEXT DEFAULT '', created_at TEXT,
    req_note TEXT DEFAULT '', depts TEXT DEFAULT '', email TEXT DEFAULT ''
);
CREATE TABLE IF NOT EXISTS public.uploads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT, dept TEXT, kind TEXT, week TEXT, orig_name TEXT,
    stored_name TEXT, size BIGINT, status TEXT, note TEXT, uploaded_at TEXT
);
CREATE TABLE IF NOT EXISTS public.weeks (
    label TEXT PRIMARY KEY, title TEXT, published INTEGER DEFAULT 0,
    published_at TEXT, comment TEXT DEFAULT ''
);
CREATE TABLE IF NOT EXISTS public.audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at TEXT, "user" TEXT, action TEXT, detail TEXT
);
CREATE TABLE IF NOT EXISTS public.hr_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept TEXT, user_id BIGINT, name TEXT, sabun TEXT DEFAULT '', kind TEXT, date TEXT,
    to_org TEXT DEFAULT '', memo TEXT DEFAULT '', status TEXT DEFAULT '접수',
    admin_note TEXT DEFAULT '', created_at TEXT, updated_at TEXT
);
CREATE TABLE IF NOT EXISTS public.settings (key TEXT PRIMARY KEY, value TEXT);
CREATE TABLE IF NOT EXISTS public.mail_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at TEXT, week TEXT, user_id BIGINT, email TEXT, subject TEXT,
    mode TEXT, ok INTEGER, err TEXT DEFAULT ''
);
CREATE INDEX IF NOT EXISTS uploads_week_status ON public.uploads(week, status);
CREATE INDEX IF NOT EXISTS hr_notes_status ON public.hr_notes(status);
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.uploads ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.weeks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.hr_notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mail_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.users, public.uploads, public.weeks, public.audit,
    public.hr_notes, public.settings, public.mail_log FROM anon, authenticated;

CREATE TABLE IF NOT EXISTS public.file_objects (
    path TEXT PRIMARY KEY, object_key TEXT NOT NULL, sha256 TEXT NOT NULL,
    size BIGINT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS public.upload_tickets (
    id TEXT PRIMARY KEY, user_id BIGINT NOT NULL, object_key TEXT NOT NULL,
    name TEXT NOT NULL, kind TEXT NOT NULL, dept TEXT NOT NULL, week TEXT NOT NULL,
    size BIGINT NOT NULL, split INTEGER DEFAULT 0, state TEXT NOT NULL DEFAULT 'issued',
    lease_until BIGINT NOT NULL DEFAULT 0, lease_token TEXT DEFAULT '',
    expires_at BIGINT NOT NULL, result TEXT DEFAULT ''
);
CREATE TABLE IF NOT EXISTS public.calc_jobs (
    id TEXT PRIMARY KEY, sequence BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE, label TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'running',
    step INTEGER NOT NULL DEFAULT 0, by_user TEXT NOT NULL, started TEXT NOT NULL,
    finished TEXT DEFAULT '', lease_until BIGINT NOT NULL DEFAULT 0,
    lease_token TEXT DEFAULT '', detail TEXT DEFAULT '{}', artifacts TEXT DEFAULT '{}'
);
CREATE UNIQUE INDEX IF NOT EXISTS calc_jobs_one_running ON public.calc_jobs((1)) WHERE state='running';
ALTER TABLE public.calc_jobs ADD COLUMN IF NOT EXISTS sequence BIGINT GENERATED ALWAYS AS IDENTITY;
ALTER TABLE public.upload_tickets ADD COLUMN IF NOT EXISTS split INTEGER DEFAULT 0;
ALTER TABLE public.weeks ADD COLUMN IF NOT EXISTS draft_job TEXT;
ALTER TABLE public.weeks ADD COLUMN IF NOT EXISTS published_job TEXT;
ALTER TABLE public.uploads ADD COLUMN IF NOT EXISTS ticket_id TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS uploads_ticket_id ON public.uploads(ticket_id);
ALTER TABLE public.uploads ADD COLUMN IF NOT EXISTS preview_json TEXT DEFAULT '';
ALTER TABLE public.uploads ADD COLUMN IF NOT EXISTS preview_lease BIGINT DEFAULT 0;
ALTER TABLE public.uploads ADD COLUMN IF NOT EXISTS preview_token TEXT DEFAULT '';
ALTER TABLE public.file_objects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.upload_tickets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.calc_jobs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.file_objects, public.upload_tickets, public.calc_jobs FROM anon, authenticated;

-- 관계와 삭제 규칙: 계정을 지워도 업무 이력·작성자 이름은 보존한다.
ALTER TABLE public.upload_tickets ALTER COLUMN user_id DROP NOT NULL;
ALTER TABLE public.calc_jobs ADD COLUMN IF NOT EXISTS user_id BIGINT;
UPDATE public.calc_jobs j SET user_id=u.id
    FROM public.users u
    WHERE j.user_id IS NULL AND j.by_user=u.username AND j.started>=COALESCE(u.created_at,'');

