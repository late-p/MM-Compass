-- 기존 데이터부터 검증하고 적용한다. 문제가 있으면 전체 마이그레이션이 롤백된다.
-- 주차/계산본의 양방향 참조는 같은 트랜잭션 안에서 생성·정리할 수 있도록 지연 검사한다.
DO $$
DECLARE relation RECORD;
BEGIN
    FOR relation IN SELECT * FROM (VALUES
        ('uploads_user_id_fkey','public.uploads',
            'FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED'),
        ('hr_notes_user_id_fkey','public.hr_notes',
            'FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED'),
        ('mail_log_user_id_fkey','public.mail_log',
            'FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED'),
        ('upload_tickets_user_id_fkey','public.upload_tickets',
            'FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED'),
        ('calc_jobs_user_id_fkey','public.calc_jobs',
            'FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED'),
        ('uploads_week_fkey','public.uploads',
            'FOREIGN KEY (week) REFERENCES public.weeks(label) DEFERRABLE INITIALLY DEFERRED'),
        ('upload_tickets_week_fkey','public.upload_tickets',
            'FOREIGN KEY (week) REFERENCES public.weeks(label) DEFERRABLE INITIALLY DEFERRED'),
        ('calc_jobs_label_fkey','public.calc_jobs',
            'FOREIGN KEY (label) REFERENCES public.weeks(label) DEFERRABLE INITIALLY DEFERRED'),
        ('weeks_draft_job_fkey','public.weeks',
            'FOREIGN KEY (label,draft_job) REFERENCES public.calc_jobs(label,id) DEFERRABLE INITIALLY DEFERRED'),
        ('weeks_published_job_fkey','public.weeks',
            'FOREIGN KEY (label,published_job) REFERENCES public.calc_jobs(label,id) DEFERRABLE INITIALLY DEFERRED')
    ) AS definitions(constraint_name,table_name,definition)
    LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname=relation.constraint_name AND conrelid=relation.table_name::regclass) THEN
            EXECUTE format('ALTER TABLE %s ADD CONSTRAINT %I %s NOT VALID',relation.table_name,relation.constraint_name,relation.definition);
        END IF;
        EXECUTE format('ALTER TABLE %s VALIDATE CONSTRAINT %I',relation.table_name,relation.constraint_name);
    END LOOP;
END $$;
